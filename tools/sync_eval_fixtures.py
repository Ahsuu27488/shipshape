"""Copy tests/fixtures/tinyshop.sh into every eval case that needs a fixture, as fixture.sh.

claude plugin eval runs a case's scaffold script from the case's own folder, so each case carries its own copy.
Each case says which fixture it wants in a one-line file `fixture-mode` (adopted | plain | empty).
  python tools/sync_eval_fixtures.py          # write the copies
  python tools/sync_eval_fixtures.py --check  # fail if any copy is stale (CI)
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "tests" / "fixtures" / "tinyshop.sh"
HEADER = "#!/bin/sh\n# GENERATED by tools/sync_eval_fixtures.py from tests/fixtures/tinyshop.sh - edit that file instead.\n"


def render(mode: str) -> str:
    body = SOURCE.read_text(encoding="utf-8").split("\n", 1)[1]  # drop the shebang
    return HEADER + f"set -- . {mode}\n" + body


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for mode_file in sorted((ROOT / "evals").glob("*/fixture-mode")):
        case = mode_file.parent
        want = render(mode_file.read_text(encoding="utf-8").strip())
        target = case / "fixture.sh"
        if target.exists() and target.read_text(encoding="utf-8") == want:
            continue
        if check:
            stale.append(case.name)
        else:
            target.write_text(want, encoding="utf-8", newline="\n")
            print(f"wrote {target.relative_to(ROOT)}")
    if stale:
        print("stale eval fixtures (run python tools/sync_eval_fixtures.py):", ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
